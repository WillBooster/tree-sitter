import { C, INTERNAL, LogCallback, ParseCallback, Range, SIZE_OF_RANGE, setModule } from './constants';
import { Language } from './language';
import { marshalRange, unmarshalRanges } from './marshal';
import { checkModule, initializeBinding, type ParserInitOptions } from './bindings';
import { Tree } from './tree';
import { newFinalizer } from './finalization_registry';

/**
 * Options for parsing
 *
 * The `includedRanges` property is an array of {@link Range} objects that
 * represent the ranges of text that the parser should include when parsing.
 *
 * The `progressCallback` property is a function that is called periodically
 * during parsing to check whether parsing should be cancelled.
 *
 * See {@link Parser#parse} for more information.
 */
export interface ParseOptions {
  /**
   * An array of {@link Range} objects that
   * represent the ranges of text that the parser should include when parsing.
   *
   * This sets the ranges of text that the parser should include when parsing.
   * By default, the parser will always include entire documents. This
   * function allows you to parse only a *portion* of a document but
   * still return a syntax tree whose ranges match up with the document
   * as a whole. You can also pass multiple disjoint ranges.
   * If `ranges` is empty, then the entire document will be parsed.
   * Otherwise, the given ranges must be ordered from earliest to latest
   * in the document, and they must not overlap. That is, the following
   * must hold for all `i` < `length - 1`:
   * ```text
   *     ranges[i].end_byte <= ranges[i + 1].start_byte
   * ```
   */
  includedRanges?: Range[];

  /**
   * A function that is called periodically during parsing to check
   * whether parsing should be cancelled. If the progress callback returns
   * `true`, then parsing will be cancelled. You can also use this to instrument
   * parsing and check where the parser is at in the document. The progress callback
   * takes a single argument, which is a {@link ParseState} representing the current
   * state of the parser.
   */
  // eslint-disable-next-line @typescript-eslint/no-invalid-void-type -- A callback may record progress without returning a cancellation decision.
  progressCallback?: (state: ParseState) => boolean | void;

  /**
   * The maximum size of Wasm memory during this parse, in bytes. Reaching it
   * cancels the parse. Memory is shared by all parsers and does not shrink, so
   * a parse also returns `null` when memory already exceeds this limit.
   */
  maxMemoryBytes?: number;
}

/**
 * A stateful object that is passed into the progress callback {@link ParseOptions#progressCallback}
 * to provide the current state of the parser.
 */
export interface ParseState {
  /** The byte offset in the document that the parser is at. */
  currentOffset: number;

  /** Indicates whether the parser has encountered an error during parsing. */
  hasError: boolean;
}

/**
 * @internal
 *
 * Global variable for transferring data across the FFI boundary
 */
export let TRANSFER_BUFFER: number;

/**
 * The latest ABI version that the current version of the library supports. The
 * CLI of this fork assigns it to each generated language. Its upper 16 bits
 * (`0x5742`, "WB") tag the fork and its lower 16 bits count the fork's ABI
 * revisions, so that it never equals an ABI version of upstream Tree-sitter:
 * the library rejects languages generated by upstream's CLI, and upstream's
 * library rejects languages generated by this fork's CLI.
 */
export let LANGUAGE_VERSION: number;

/**
 * @internal
 *
 * Throws unless the CLI of this fork generated the language.
 */
export function assertSupportedLanguage(language: Language): void {
  const version = C._ts_language_abi_version(language[0]);
  if (version < MIN_COMPATIBLE_VERSION || version > LANGUAGE_VERSION) {
    throw new Error(
      `Incompatible language version 0x${(version >>> 0).toString(16)}. ` +
      `Expected 0x${LANGUAGE_VERSION.toString(16)}.`
    );
  }
}

/**
 * The earliest ABI version that is supported by the current version of the
 * library. Its parse tables are a subset of those of {@link LANGUAGE_VERSION},
 * so the library loads both.
 */
export let MIN_COMPATIBLE_VERSION: number;

const finalizer = newFinalizer((addresses: number[]) => {
  C._ts_parser_delete(addresses[0]);
  C._free(addresses[1]);
});

/**
 * A stateful object that is used to produce a {@link Tree} based on some
 * source code.
 */
export class Parser {
  /** @internal */
  private [0] = 0; // Internal handle for Wasm

  /** @internal */
  private [1] = 0; // Internal handle for Wasm

  /** @internal */
  private logCallback: LogCallback | null = null;

  /** @internal */
  private loggerEnabled = false;

  /** @internal */
  private hasIncludedRanges = false;

  /** The parser's current language. */
  language: Language | null = null;

  /**
   * This must always be called before creating a Parser.
   *
   * You can optionally pass in options to configure the Wasm module, the most common
   * one being `locateFile` to help the module find the `.wasm` file. In Cloudflare Workers,
   * pass the imported `web-tree-sitter.wasm` module as `wasmModule` instead.
   */
  static async init(options?: ParserInitOptions) {
    setModule(await initializeBinding(options));
    TRANSFER_BUFFER = C._ts_init();
    const idx = TRANSFER_BUFFER >> 2;
    LANGUAGE_VERSION = C.HEAP32[idx];
    MIN_COMPATIBLE_VERSION = C.HEAP32[idx + 1];
  }

  /**
   * Create a new parser.
   */
  constructor() {
    this.initialize();
    finalizer?.register(this, [this[0], this[1]], this);
  }

  /** @internal */
  initialize() {
    if (!checkModule()) {
      throw new Error("cannot construct a Parser before calling `init()`");
    }
    C._ts_parser_new_wasm();
    const idx = TRANSFER_BUFFER >> 2;
    this[0] = C.HEAP32[idx];
    this[1] = C.HEAP32[idx + 1];
  }

  /** Delete the parser, freeing its resources. */
  delete() {
    finalizer?.unregister(this);
    C._ts_parser_delete(this[0]);
    C._free(this[1]);
    this[0] = 0;
    this[1] = 0;
  }

  /**
   * Set the language that the parser should use for parsing.
   *
   * If the language was not successfully assigned, an error will be thrown.
   * This happens if the language was generated with an incompatible
   * version of the Tree-sitter CLI. Check the language's version using
   * {@link Language#abiVersion}; this library accepts versions from
   * {@link MIN_COMPATIBLE_VERSION} to {@link LANGUAGE_VERSION}.
   */
  setLanguage(language: Language | null): this {
    let address: number;
    if (!language) {
      address = 0;
      this.language = null;
    } else if (language.constructor === Language) {
      address = language[0];
      assertSupportedLanguage(language);
      this.language = language;
    } else {
      throw new Error('Argument must be a Language');
    }

    C._ts_parser_set_language(this[0], address);
    return this;
  }

  /**
   * Parse a slice of UTF8 text.
   *
   * @param {string | ParseCallback} callback - The UTF8-encoded text to parse or a callback function.
   *
   * @param {Tree | null} [oldTree] - A previous syntax tree parsed from the same document. If the text of the
   *   document has changed since `oldTree` was created, then you must edit `oldTree` to match
   *   the new text using {@link Tree#edit}.
   *
   * @param {ParseOptions} [options] - Options for parsing the text.
   *  This can be used to set the included ranges, or a progress callback.
   *
   * @returns {Tree | null} A {@link Tree} if parsing succeeded, or `null` if:
   *  - The parser has not yet had a language assigned with {@link Parser#setLanguage}.
   *  - The progress callback returned true.
   *  - The memory limit was reached.
   */
  parse(
    callback: string | ParseCallback,
    oldTree?: Tree | null,
    options?: ParseOptions,
  ): Tree | null {
    const maxMemoryBytes = validateMemoryLimit(options?.maxMemoryBytes);
    if (typeof callback !== 'string' && typeof callback !== 'function') {
      throw new Error('Argument must be a string or a function');
    }

    const progressCallback = options?.progressCallback ?? null;
    C.currentProgressCallback = progressCallback;
    this.syncLogger();

    try {
      const treeAddress = this.runParse(callback, oldTree, options?.includedRanges, maxMemoryBytes, Boolean(progressCallback));
      if (!treeAddress) return null;
      if (!this.language) throw new Error('Parser must have a language to parse');
      return new Tree(INTERNAL, treeAddress, this.language, callback);
    } finally {
      clearCallbacks();
    }
  }

  /** @internal */
  private syncLogger(): void {
    if (this.logCallback) {
      C.currentLogCallback = this.logCallback;
      if (!this.loggerEnabled) {
        C._ts_parser_enable_logger_wasm(this[0], 1);
        this.loggerEnabled = true;
      }
    } else {
      C.currentLogCallback = null;
      if (this.loggerEnabled) {
        C._ts_parser_enable_logger_wasm(this[0], 0);
        this.loggerEnabled = false;
      }
    }
  }

  /** @internal */
  private runParse(
    callback: string | ParseCallback,
    oldTree: Tree | null | undefined,
    includedRanges: Range[] | undefined,
    maxMemoryBytes: number | undefined,
    hasProgressCallback: boolean,
  ): number {
    if (maxMemoryBytes !== undefined) {
      C.currentParseCallback = typeof callback === 'string'
        ? (index: number) => callback.slice(index, index + CHUNK_CODE_UNITS)
        : callback;
      const treeAddress = parseLimitedWasm(this[0], this[1], includedRanges, maxMemoryBytes, hasProgressCallback);
      if (treeAddress) this.hasIncludedRanges = Boolean(includedRanges?.length);
      return treeAddress;
    }

    if (!this.syncIncludedRanges(includedRanges)) return 0;
    if (!this.language) return 0;
    const oldTreeAddress = oldTree ? oldTree[0] : 0;

    if (typeof callback === 'string' && !hasProgressCallback && !this.hasIncludedRanges && callback.length <= MAX_DIRECT_STRING_CODE_UNITS) {
      return parseStringWasm(this[0], this[1], oldTreeAddress, callback);
    }

    C.currentParseCallback = typeof callback === 'string'
      ? (index: number) => callback.slice(index, index + CHUNK_CODE_UNITS)
      : callback;
    return C._ts_parser_parse_wasm(this[0], this[1], oldTreeAddress, hasProgressCallback ? 1 : 0);
  }

  /** @internal */
  private syncIncludedRanges(ranges?: Range[]): boolean {
    if (ranges?.length) {
      const [rangeAddress, rangeCount] = prepareRanges(ranges);
      if (!rangeAddress) return false;
      C._ts_parser_set_included_ranges_wasm(this[0], rangeAddress, rangeCount);
      this.hasIncludedRanges = true;
    } else if (this.hasIncludedRanges) {
      C._ts_parser_set_included_ranges_wasm(this[0], 0, 0);
      this.hasIncludedRanges = false;
    }
    return true;
  }

  /**
   * Instruct the parser to start the next parse from the beginning.
   *
   * If the parser previously failed because of a callback, 
   * then by default, it will resume where it left off on the
   * next call to {@link Parser#parse} or other parsing functions.
   * If you don't want to resume, and instead intend to use this parser to
   * parse some other document, you must call `reset` first.
   */
  reset(): void {
    C._ts_parser_reset(this[0]);
  }

  /** Get the ranges of text that the parser will include when parsing. */
  getIncludedRanges(): Range[] {
    C._ts_parser_included_ranges_wasm(this[0]);
    return unmarshalRanges(false);
  }

  /** Set the logging callback that a parser should use during parsing. */
  setLogger(callback: LogCallback | boolean | null): this {
    if (!callback) {
      this.logCallback = null;
    } else if (typeof callback !== 'function') {
      throw new Error('Logger callback must be a function');
    } else {
      this.logCallback = callback;
    }
    return this;
  }

  /** Get the parser's current logger. */
  getLogger(): LogCallback | null {
    return this.logCallback;
  }
}

const INPUT_BUFFER_CODE_UNITS = (10 * 1024) >> 1;
const CHUNK_CODE_UNITS = INPUT_BUFFER_CODE_UNITS - 1;
const MAX_DIRECT_STRING_CODE_UNITS = 16 * 1024 * 1024;

function validateMemoryLimit(maxMemoryBytes?: number): number | undefined {
  if (maxMemoryBytes !== undefined &&
    (!Number.isSafeInteger(maxMemoryBytes) || maxMemoryBytes <= 0 || maxMemoryBytes > 0x7fffffff)) {
    throw new RangeError('maxMemoryBytes must be a positive integer no greater than 2147483647');
  }
  return maxMemoryBytes;
}

function prepareRanges(ranges?: Range[]): [number, number] {
  if (!ranges?.length) return [0, 0];
  const rangeAddress = C._calloc(ranges.length, SIZE_OF_RANGE);
  if (!rangeAddress) return [0, ranges.length];
  let address = rangeAddress;
  for (const range of ranges) {
    marshalRange(address, range);
    address += SIZE_OF_RANGE;
  }
  return [rangeAddress, ranges.length];
}

function parseStringWasm(
  parserAddress: number,
  inputBuffer: number,
  oldTreeAddress: number,
  source: string,
): number {
  const length = source.length;
  const byteLength = length * 2;
  const allocatedBuffer = length > INPUT_BUFFER_CODE_UNITS ? C._malloc(byteLength) : 0;
  if (length > INPUT_BUFFER_CODE_UNITS && !allocatedBuffer) return 0;
  try {
    const bufferAddress = allocatedBuffer || inputBuffer;
    const heapU16 = C.HEAPU16;
    const base = bufferAddress >>> 1;
    for (let i = 0; i < length; i++) {
      heapU16[base + i] = source.charCodeAt(i);
    }
    return C._ts_parser_parse_string_wasm(parserAddress, oldTreeAddress, bufferAddress, byteLength);
  } finally {
    if (allocatedBuffer) C._free(allocatedBuffer);
  }
}

function parseLimitedWasm(
  parserAddress: number,
  inputBuffer: number,
  ranges: Range[] | undefined,
  maxMemoryBytes: number,
  hasProgressCallback: boolean,
): number {
  if (!C.treeSitterSetMemoryLimit(maxMemoryBytes)) return 0;
  let rangeAddress = 0;
  try {
    const [address, rangeCount] = prepareRanges(ranges);
    rangeAddress = address;
    if (rangeCount && !address) return 0;
    try {
      return C._ts_parser_parse_limited_wasm(
        parserAddress,
        inputBuffer,
        address,
        rangeCount,
        hasProgressCallback ? 1 : 0,
      );
    } catch (error) {
      C._ts_parser_abort_limited_wasm();
      throw error;
    }
  } finally {
    if (rangeAddress) C._free(rangeAddress);
    C.treeSitterSetMemoryLimit(0);
  }
}

function clearCallbacks(): void {
  C.currentParseCallback = null;
  C.currentLogCallback = null;
  C.currentProgressCallback = null;
}
