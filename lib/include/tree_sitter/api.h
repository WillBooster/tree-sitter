/****************************/
/* Section - ABI Versioning */
/****************************/

/**
 * The latest ABI version that the current version of the library supports. The
 * CLI of this fork assigns it to each generated language. Its upper 16 bits
 * (`0x5742`, "WB") tag the fork and its lower 16 bits count the fork's ABI
 * revisions, so that it never equals an ABI version of upstream Tree-sitter:
 * the library rejects languages generated by upstream's CLI, and upstream's
 * library rejects languages generated by this fork's CLI.
 */
#define TREE_SITTER_LANGUAGE_VERSION 0x5742000c

/**
 * The earliest ABI version that is supported by the current version of the
 * library. Its parse tables are a subset of those of
 * [`TREE_SITTER_LANGUAGE_VERSION`], so the library loads both.
 */
#define TREE_SITTER_MIN_COMPATIBLE_LANGUAGE_VERSION 0x5742000b

